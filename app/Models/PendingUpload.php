<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

/**
 * A photo that is being uploaded straight to the bucket.
 *
 * The row is created before the browser starts the upload, so the space the
 * photo needs can be reserved in the quota and the upload can be completed
 * (and cleaned up) later on.
 */
#[Fillable([
    'id',
    'user_id',
    'album_id',
    'is_private',
    'original_filename',
    'mime_type',
    'size_bytes',
    'incoming_path',
    'alt_text',
    'tags',
    'status',
    'expires_at',
])]
class PendingUpload extends Model
{
    /**
     * The upload is waiting for the browser to send the file.
     */
    public const STATUS_PENDING = 'pending';

    /**
     * The file arrived and was registered as a photo.
     */
    public const STATUS_COMPLETED = 'completed';

    /**
     * The upload was refused or abandoned; the temporary file was removed.
     */
    public const STATUS_FAILED = 'failed';

    /**
     * The identifier is generated by the application, not by the database.
     */
    public $incrementing = false;

    protected $keyType = 'string';

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'is_private' => 'boolean',
            'size_bytes' => 'integer',
            'tags' => 'array',
            'expires_at' => 'datetime',
        ];
    }

    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function album(): BelongsTo
    {
        return $this->belongsTo(Album::class);
    }

    /**
     * Whether the browser had enough time to send the file.
     */
    public function isExpired(): bool
    {
        return $this->expires_at !== null && $this->expires_at->isPast();
    }
}
